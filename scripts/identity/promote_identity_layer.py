"""
GoodQ4All — Phase 5A: Person Identity Node Promotion
=====================================================
The ONLY script that writes to knowledge_graph.db.

Pre-conditions (all enforced):
  1. validate_roster.py exits 0
  2. --epoch-id matches the active epoch
  3. KG backup is taken before any write
  4. --dry-run pass is completed and output reviewed
  5. --confirm flag required for actual execution

This script promotes PERSON NODES ONLY.
Holiday/place/event context nodes are Phase 5B (separate script).

Usage — dry-run first (required):
    conda run -n goodq_core python scripts/identity/promote_identity_layer.py \\
        --epoch-id epoch_2026_07_05_home_memory_clean_01 \\
        --dry-run \\
        [--data-path L:/_DATA/GoodQ_Data/identity]

Usage — actual promotion (only after dry-run review):
    conda run -n goodq_core python scripts/identity/promote_identity_layer.py \\
        --epoch-id epoch_2026_07_05_home_memory_clean_01 \\
        --confirm \\
        [--data-path L:/_DATA/GoodQ_Data/identity]

Rollback:
    See reports/identity/ROLLBACK.md generated by dry-run.
"""

